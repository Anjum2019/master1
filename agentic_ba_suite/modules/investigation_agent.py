"""
Reporting Investigation Assistant
Helps business analysts organise reporting issues, compare expected vs actual figures,
isolate root causes across Power BI and SQL databases, formulate SQL diagnostic scripts,
and generate ready-to-use Jira tickets and stakeholder communication drafts.
"""

from datetime import datetime

def run_reporting_investigation(
    ticket_id: str,
    reporting_system: str,
    backend_system: str,
    metric_name: str,
    expected_value: float,
    actual_value: float,
    currency: str,
    filter_context: str,
    symptoms: str,
    suspected_layer: str = "Auto-Detect"
) -> dict:
    """
    Executes an intelligent triage workflow for reporting discrepancies.
    """
    delta = actual_value - expected_value
    delta_pct = (delta / expected_value * 100) if expected_value != 0 else 0.0
    abs_delta = abs(delta)
    abs_pct = abs(delta_pct)

    # 1. Determine Severity
    if abs_pct > 10.0 or abs_delta > 250000:
        severity = "P1 - Critical (Executive Escalation)"
        sla = "4 Hours"
        badge = "🚨 CRITICAL DISCREPANCY"
    elif abs_pct > 2.0 or abs_delta > 50000:
        severity = "P2 - High (Business Impairment)"
        sla = "8 Hours"
        badge = "⚠️ HIGH SEVERITY"
    else:
        severity = "P3 - Medium (Variance Analysis)"
        sla = "24 Hours"
        badge = "ℹ️ MODERATE VARIANCE"

    # 2. Diagnose Layer & Root Cause
    sym_lower = (symptoms + " " + suspected_layer).lower()
    
    if "migration" in sym_lower or "duplicate" in sym_lower or "join" in sym_lower:
        likely_layer = "SQL Database / Data Warehouse (Join Cardinality or Migration Staging)"
        confidence = "88%"
        cause_desc = "Cartesian product or duplicate primary keys introduced during data migration or dimension table join."
        sql_focus = "Check for duplicate project_id records in Dim_Project or Many-to-Many relationship fan-out."
    elif "code" in sym_lower or "unmapped" in sym_lower or "missing project" in sym_lower or "orphan" in sym_lower:
        likely_layer = "SQL Data Warehouse / Dimension Mapping"
        confidence = "92%"
        cause_desc = "New transaction records in Fact tables reference project or client codes that have not yet been synced or mapped in Dim_Project, causing Power BI inner-joins or relationship filters to silently drop them."
        sql_focus = "Identify orphaned records in Fact_Project_Financials where Dim_Project.Project_Key IS NULL."
    elif "timing" in sym_lower or "refresh" in sym_lower or "yesterday" in sym_lower or "etl" in sym_lower or "batch" in sym_lower:
        likely_layer = "ETL Pipeline / Scheduled Gateway Refresh"
        confidence = "85%"
        cause_desc = "Scheduled overnight incremental ETL pipeline failed or completed with partial batch staging before Power BI dataset refresh triggered."
        sql_focus = "Query sys_etl_watermark and compare Last_Modified_Date in ERP vs Data Warehouse."
    elif "currency" in sym_lower or "fx" in sym_lower or "conversion" in sym_lower or "rate" in sym_lower:
        likely_layer = "Data Model (FX Exchange Rate Lookup Table)"
        confidence = "80%"
        cause_desc = "Power BI DAX measure evaluates currency conversion using spot rate while source ERP reports in fixed month-end corporate ledger rates."
        sql_focus = "Validate currency rate lookup mapping between Dim_Exchange_Rates and Fact_Transactions."
    elif "subtotal" in sym_lower or "dax" in sym_lower or "measure" in sym_lower or "filter" in sym_lower or "slicer" in sym_lower:
        likely_layer = "Power BI Reporting Layer (DAX Calculation Context)"
        confidence = "87%"
        cause_desc = "DAX Measure utilizes CALCULATE with ALLSELECTED or insufficient filter context removal, leading to incorrect visual-level aggregation or incorrect total card evaluation."
        sql_focus = "Compare raw SUM(Amount) from SQL view against Power BI DAX measure logic."
    else:
        likely_layer = "Hybrid: Power BI DAX Filter Context vs Underlying SQL View"
        confidence = "75%"
        cause_desc = "Discrepancy likely driven by a mismatch between report-level slicers and SQL view WHERE clause predicates."
        sql_focus = "Execute baseline reconciliation query grouping by the active report filter dimensions."

    # 3. Generate Diagnostic SQL Queries
    sql_script = f"""-- ========================================================================
-- ENTERPRISE REPORTING INVESTIGATION DIAGNOSTIC SUITE
-- Ticket: {ticket_id} | System: {reporting_system} -> {backend_system}
-- Target Metric: {metric_name} | Expected: {expected_value:,.2f} | Actual: {actual_value:,.2f}
-- Generated by Autonomous Reporting Investigation Assistant
-- ========================================================================

-- STEP 1: Check for Orphaned Fact Records (Transactions without Dimension Keys)
SELECT 
    f.project_code,
    f.cost_center,
    COUNT(*) AS unmapped_row_count,
    SUM(f.financial_amount) AS missing_revenue_exposure
FROM dw_financials.fact_project_ledger f
LEFT JOIN dw_financials.dim_project d 
    ON f.project_key = d.project_key
WHERE d.project_key IS NULL
  AND f.transaction_date >= DATEADD(month, -3, GETDATE())
GROUP BY f.project_code, f.cost_center
HAVING SUM(f.financial_amount) <> 0;

-- STEP 2: Ground-Truth Direct Source Reconciliation Query
-- Mirrors Power BI Filter Context: {filter_context}
SELECT 
    d.business_unit,
    d.sub_portfolio,
    COUNT(DISTINCT f.transaction_id) AS total_transactions,
    SUM(f.billed_amount) AS raw_billed_amount,
    SUM(f.unbilled_wip) AS raw_wip_amount,
    SUM(f.total_recognized_revenue) AS sql_ground_truth_revenue
FROM dw_financials.fact_project_ledger f
INNER JOIN dw_financials.dim_project d 
    ON f.project_key = d.project_key
INNER JOIN dw_financials.dim_date dt 
    ON f.date_key = dt.date_key
WHERE dt.fiscal_quarter = 'Q3-2026'
  -- Replicating active report slicer context:
  -- {filter_context}
GROUP BY d.business_unit, d.sub_portfolio
ORDER BY sql_ground_truth_revenue DESC;

-- STEP 3: Verify ETL Pipeline Watermark & Refresh Timestamps
SELECT 
    pipeline_name,
    source_table_name,
    target_table_name,
    last_extract_timestamp,
    last_load_timestamp,
    rows_extracted,
    rows_loaded,
    pipeline_status
FROM dw_audit.etl_pipeline_execution_log
WHERE pipeline_name LIKE '%Financial%'
ORDER BY last_load_timestamp DESC
FETCH FIRST 5 ROWS ONLY;
"""

    # 4. Generate Jira / ServiceNow Ticket
    jira_markdown = f"""### 🎫 [JIRA / SERVICENOW DEFECT SPECIFICATION]
**Issue Key:** `{ticket_id}`  
**Summary:** [Triage] {reporting_system} - {metric_name} discrepancy of {currency} {abs_delta:,.2f} ({delta_pct:+.2f}%)  
**Issue Type:** Reporting Defect / Data Discrepancy  
**Severity:** `{severity}` (Target SLA: {sla})  
**Component:** BI Reporting Platform / SQL Data Warehouse  
**Reporter:** Senior Business Analyst (Reporting & Insights)  
**Assignee:** Data Engineering & BI Development Team  

#### 1. Business Impact & Description
During executive reporting reviews, a material discrepancy was flagged between the front-end **{reporting_system}** and source **{backend_system}**.  
- **Metric in Question:** `{metric_name}`
- **Active Slicer/Filter Context:** `{filter_context}`
- **Expected Value (Finance Source Ledger):** `{currency} {expected_value:,.2f}`
- **Actual Reported Value ({reporting_system}):** `{currency} {actual_value:,.2f}`
- **Discrepancy (Delta):** `{currency} {delta:+,.2f}` (`{delta_pct:+.2f}%`)
- **Symptoms / User Feedback:** {symptoms}

#### 2. Root Cause Analysis (BA Triage)
- **Primary Suspected Layer:** `{likely_layer}` (Confidence: **{confidence}**)
- **Functional Explanation:** {cause_desc}
- **Investigative Finding:** The front-end calculation excludes newly onboarded records or suffers from a filter-context drop. Data in source ERP reflects the higher expected value.

#### 3. Steps to Reproduce
1. Open `{reporting_system}` -> Navigate to Portfolio Executive Overview page.
2. Apply filter context: `{filter_context}`.
3. Observe metric tile `{metric_name}` displaying `{currency} {actual_value:,.2f}`.
4. Run validation query on `{backend_system}` table `dw_financials.fact_project_ledger`; query returns `{currency} {expected_value:,.2f}`.

#### 4. Acceptance Criteria
- [ ] SQL view / DAX measure is updated to reconcile orphaned dimension keys or correct filter context.
- [ ] Direct query and imported tabular cache show exact match to Source Ledger within 0.01% rounding tolerance.
- [ ] ETL audit checks added to prevent future unmapped project codes from bypassing notification alerts.
- [ ] Regression testing performed across adjacent quarterly portfolio views.
"""

    # 5. Stakeholder Communication Draft
    comm_draft = f"""**Subject:** UPDATE: Triage & Resolution Plan for {metric_name} Reporting Query [{ticket_id}]

**Dear Project Delivery Leadership & Finance Operations Team,**

Thank you for bringing the variance in the **{reporting_system}** ({metric_name}) to our attention. Our team has completed the initial business analysis and technical triage:

**Summary of Investigation:**
• **Metric Examined:** {metric_name} ({filter_context})
• **Source Ledger Figure:** {currency} {expected_value:,.2f}
• **Dashboard Display:** {currency} {actual_value:,.2f}
• **Variance Identified:** {currency} {abs_delta:,.2f} ({abs_pct:.2f}%)

**Root Cause & Immediate Action:**
We have isolated the source of the variance to: **{likely_layer}**. 
Specifically, {cause_desc}
Please be assured that underlying source transactions are secure and intact. This is an aggregation and presentation mapping issue rather than financial transaction loss.

**Next Steps & Resolution ETA:**
1. Ticket **{ticket_id}** has been raised with priority **{severity}**.
2. We have provided the engineering team with exact SQL verification scripts to update the dimension mapping.
3. A patched data model refresh is targeted within **{sla}**. We will run functional validation before confirming completion.

We will share a confirmation update as soon as the refreshed figures are live in the production workspace.

Best regards,  
**Senior Business Analyst — Reporting & Insights**  
Financial Operations & BI Analytics Platform
"""

    triage_overview_md = f"""### {badge}
**Ticket Reference:** `{ticket_id}` | **Assigned SLA:** `{sla}`  
**Assessed Severity:** `{severity}`

| Dimension | Specification |
| :--- | :--- |
| **Reporting Interface** | `{reporting_system}` |
| **Underlying Data Store** | `{backend_system}` |
| **Metric Analyzed** | `{metric_name}` |
| **Expected Value (Ledger/SOW)** | **{currency} {expected_value:,.2f}** |
| **Actual Value (Reported)** | **{currency} {actual_value:,.2f}** |
| **Variance Delta** | **{currency} {delta:+,.2f} ({delta_pct:+.2f}%)** |
| **Suspected Fault Layer** | **{likely_layer}** (Confidence: {confidence}) |

---
**Initial Assessment:**  
{cause_desc}
"""

    return {
        "triage_overview_md": triage_overview_md,
        "sql_script": sql_script,
        "jira_markdown": jira_markdown,
        "comm_draft": comm_draft,
        "severity": severity,
        "delta_info": f"{currency} {delta:+,.2f} ({delta_pct:+.2f}%)"
    }

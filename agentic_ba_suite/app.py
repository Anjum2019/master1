def load_investigation_scenario(scenario_key):
    if scenario_key in SCENARIOS:
        s = SCENARIOS[scenario_key]
        return (
            s["ticket_id"],
            s["system"],
            s["backend"],
            s["metric"],
            s["expected"],
            s["actual"],
            s["currency"],
            s["filter"],
            s["symptoms"],
            s["layer"]
        )
    return "", "", "", "", 0.0, 0.0, "USD", "", "", "Auto-Detect"

def process_investigation_agent(ticket_id, sys_rep, sys_back, metric, exp, act, curr, filt, symptoms, layer):
    if not ticket_id or not metric:
        return "⚠️ Please provide at least a Ticket Reference and Metric Name.", "", "", "", None

    result = run_reporting_investigation(
        ticket_id=ticket_id,
        reporting_system=sys_rep,
        backend_system=sys_back,
        metric_name=metric,
        expected_value=float(exp),
        actual_value=float(act),
        currency=curr,
        filter_context=filt,
        symptoms=symptoms,
        suspected_layer=layer
    )

    # Save complete triage dossier
    dossier = f"""# Enterprise Reporting Investigation Dossier
Generated by: Reporting Investigation Assistant

{result['triage_overview_md']}

## Diagnostic SQL Scripts
```sql
{result['sql_script']}
```

{result['jira_markdown']}

## Stakeholder Interim Communication Draft
{result['comm_draft']}
"""
    tmp_path = os.path.join(tempfile.gettempdir(), f"{ticket_id}_investigation_dossier.md")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(dossier)

    return (
        result["triage_overview_md"],
        result["sql_script"],
        result["jira_markdown"],
        result["comm_draft"],
        tmp_path
    )


def load_sample_dataset(choice):
    if choice == "Q3 Financial Portfolio (Revenue, Cost, Margin, EBITDA)":
        return pd.read_csv(FINANCIAL_CSV), "What caused the margin compression across business units, and which sectors exceeded revenue targets?"
    elif choice == "Delivery Operations & WIP Aging (Project Health & Leakage)":
        return pd.read_csv(DELIVERY_CSV), "Identify projects with critical cost overruns and WIP aging > 60 days."
    elif choice == "Financial Forecasting vs Actuals (2026 Run-Rate Analysis)":
        return pd.read_csv(FORECAST_CSV), "Explain the monthly revenue variances and identify the primary operational drivers."
    return None, ""

def process_dashboard_agent(dataset_choice, custom_file, query, tolerance):
    if custom_file is not None:
        try:
            if custom_file.name.endswith('.csv'):
                df = pd.read_csv(custom_file.name)
            else:
                df = pd.read_excel(custom_file.name)
        except Exception as e:
            return f"❌ Error loading uploaded file: {str(e)}", pd.DataFrame(), "", "", None
    else:
        df, _ = load_sample_dataset(dataset_choice)

    if df is None or df.empty:
        return "⚠️ Please select a dataset or upload a valid CSV/Excel file.", pd.DataFrame(), "", "", None

    result = analyze_dashboard_dataset(df, query, tolerance)

    # Save downloadable report
    report_content = f"""# Executive Dashboard Insights Report
Generated by: Dashboard Insights Agent
Query: {query}
Tolerance: {tolerance}%

{result['summary_md']}

{result['drivers_md']}

{result['recommendations_md']}
"""
    tmp_path = os.path.join(tempfile.gettempdir(), "dashboard_insights_report.md")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(report_content)

    return (
        result["summary_md"],
        result["variance_df"],
        result["drivers_md"],
        result["recommendations_md"],
        tmp_path
    )


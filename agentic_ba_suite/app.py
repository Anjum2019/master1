def process_web_summary_agent(url_input, direct_text_input, focus_choice):
    if direct_text_input and direct_text_input.strip():
        data = {
            "title": "Directly Supplied Enterprise Document",
            "url": "User Direct Input",
            "domain": "Enterprise Internal Text",
            "text": direct_text_input.strip(),
            "word_count": len(direct_text_input.strip().split()),
            "reading_time_min": max(1, round(len(direct_text_input.strip().split()) / 200))
        }
    elif url_input and url_input.strip():
        data = extract_web_content(url_input.strip())
    else:
        return (
            "⚠️ Please enter a URL or paste text content to summarize.",
            "",
            "",
            "",
            "",
            None
        )

    res = summarize_extracted_content(data, summary_type=focus_choice)

    # Export report
    full_export = f"""# Enterprise Web Intelligence Summary
Generated by: Website Summarisation Agent

{res['overview_md']}

{res['findings_md']}

{res['implications_md']}

{res['takeaways_md']}

---
## Raw Extracted Text Reference
{data.get('text', '')[:2000]}... [Truncated for brevity]
"""
    tmp_path = os.path.join(tempfile.gettempdir(), "web_summary_report.md")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(full_export)

    return (
        res["overview_md"],
        res["findings_md"],
        res["implications_md"],
        res["takeaways_md"],
        data.get("text", "No raw text extracted."),
        tmp_path
    )

